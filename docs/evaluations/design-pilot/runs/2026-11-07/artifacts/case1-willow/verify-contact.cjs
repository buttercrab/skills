const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/index.html','utf8');
const script = html.split('<script>')[1].split('</script>')[0];
new vm.Script(script);
const storage = new Map();
function setup(){
 const elements = new Map();
 function element(id){
  if(!elements.has(id))elements.set(id,{id,innerHTML:'',textContent:'',hidden:false,value:'',open:false,listeners:{},addEventListener(type,fn){this.listeners[type]=fn},setAttribute(k,v){this[k]=v},focus(){},querySelector(){return {focus(){}}},showModal(){this.open=true},close(){this.open=false}});
  return elements.get(id);
 }
 const filters=['Late','Ready','Collected','All'].map(filter=>({...element('filter-'+filter),dataset:{filter}}));
 const document={getElementById:element,querySelectorAll(){return filters},querySelector(selector){return selector==='.tabs'?element('tabs'):filters.find(x=>selector.includes(x.dataset.filter))}};
 const context=vm.createContext({document,structuredClone,localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)}});
 vm.runInContext(script,context);
 const evaluate=s=>vm.runInContext(s,context);
 const click=(kind,id)=>element('rows').listeners.click({target:{closest:selector=>selector===`[data-${kind}]`?{dataset:{[kind]:id}}:null}});
 return {element,evaluate,click,filters};
}
let app=setup();
const row=id=>app.element('rows').innerHTML.match(new RegExp(`<tr>(?:(?!<tr>)[\\s\\S])*?${id}(?:(?!<tr>)[\\s\\S])*?</tr>`))?.[0];
assert.equal(app.evaluate('orders.filter(o=>o.contacted).length'),0);
assert.ok(app.element('rows').innerHTML.indexOf('Kite Cafe')<app.element('rows').innerHTML.indexOf('Paper Finch'));
assert.ok(row('H-104').includes('38 min overdue'));
assert.ok(row('H-106').includes('12 min overdue'));
assert.ok(row('H-104').includes('data-call="H-104"'));
assert.match(row('H-104'),/data-collect="H-104" disabled/);
app.click('collect','H-104');
assert.equal(app.evaluate("orders[0].status"),'Late','collection guard blocks pre-contact attempt');
app.click('call','H-104');
assert.equal(app.element('call-dialog').open,true);
assert.equal(app.element('call-number').textContent,'555-0104');
assert.equal(app.element('call-delay').textContent,'38 minutes overdue');
assert.equal(app.evaluate('orders[0].contacted'),false,'opening call panel must not record contact');
app.element('cancel-call').onclick();
assert.equal(app.element('call-dialog').open,false);
assert.equal(app.evaluate('orders[0].contacted'),false,'cancel leaves contact untouched');
app.click('call','H-104');
app.element('record-call').onclick();
assert.equal(app.evaluate('orders[0].contacted'),true);
assert.equal(app.evaluate('orders[0].status'),'Late','recording contact does not collect');
assert.doesNotMatch(row('H-104'),/data-collect="H-104" disabled/);
assert.match(row('H-106'),/data-collect="H-106" disabled/,'other customer remains locked');
app=setup();
assert.equal(app.evaluate('orders[0].contacted'),true,'demo contact persists');
assert.equal(app.evaluate('orders[0].status'),'Late');
app.click('collect','H-104');
assert.equal(app.evaluate('orders[0].status'),'Collected');
assert.equal(app.element('count-Late').textContent,1);
assert.equal(app.element('count-Collected').textContent,1);
app.element('undo').onclick();
assert.equal(app.evaluate('orders[0].status'),'Late');
assert.equal(app.evaluate('orders[0].contacted'),true);
app.element('reset').onclick();
assert.equal(app.evaluate('orders.filter(o=>o.contacted).length'),0);
assert.equal(app.evaluate('orders.filter(o=>o.status==="Late").length'),2);
assert.ok(app.evaluate('orders.every(o=>o.phone.startsWith("555-"))'));
assert.ok(!/tel:|sms:|fetch\s*\(|XMLHttpRequest|window\.open/.test(html),'no outbound call/message/network implementation');
assert.ok(html.includes('Demo only — no call is placed.'));
console.log('PASS: source syntax, overdue order/durations, visible call actions, no-call panel, cancel, contact gate, separate collection, per-customer isolation, storage reload, counters, undo, reset, no outbound call/network code.');
